// PLAN A4 ("every texture has a provenance sidecar"): the reading at one commit and its markdown. census.mjs runs it for
// `--only provenance`; the status rules live in provenance.mjs. Git access (git, readBlobs) is passed in by census.mjs.
import { readProvenance, totals, TEXTURE_DIR } from './provenance.mjs';

export function provenanceReading(rev, git, readBlobs) {
  const sha = git(['rev-parse', '--verify', `${rev}^{commit}`]).toString().trim();
  const subject = git(['log', '-1', '--format=%s', sha]).toString().trim();
  const listed = git(['ls-tree', '-r', '-z', sha]).toString('utf8').split('\0').filter(Boolean).map(rec => {
    const tab = rec.indexOf('\t');
    const [, type, blob] = rec.slice(0, tab).split(' ');
    return { type, blob, path: rec.slice(tab + 1) };
  }).filter(e => e.type === 'blob' && TEXTURE_DIR.test(e.path));
  const tracked = new Set(listed.map(e => e.path));
  const wanted = listed.filter(e => e.path.endsWith('.png.provenance.txt') || e.path.endsWith('/PROVENANCE.md'));
  const blobs = readBlobs(wanted.map(e => e.blob));
  const text = new Map(wanted.map(e => [e.path, blobs.get(e.blob).toString('utf8')]));
  const records = readProvenance(tracked, p => text.get(p));
  const apps = [...new Set(records.map(r => r.app))].sort();
  const trees = Object.fromEntries(apps.map(app => [app, git(['rev-parse', `${sha}:apps/${app}/Assets/Art/Textures`]).toString().trim()]));
  return { sha, subject, records, apps, trees };
}

export function provenanceMarkdown(r) {
  const row = cells => `| ${cells.join(' | ')} |`;
  const cell = x => String(x).replace(/\|/g, '\\|').replace(/\s+/g, ' ');
  const clip = x => (x.length > 140 ? `${x.slice(0, 137)}...` : x);
  const all = totals(r.records);
  const out = [];
  out.push('# A4 provenance census', '');
  out.push(`Generated by \`node tools/assets/census.mjs --only provenance --rev ${r.sha}\`. Do not edit by hand; rerun the tool.`, '');
  out.push(`Commit read: \`${r.sha}\` (${r.subject}).`, '');
  out.push('Texture folders read, by git tree id, so the reading stays checkable after a rebase that leaves those folders alone (`git rev-parse <rev>:<folder>`):', '');
  for (const app of r.apps) out.push(`- \`apps/${app}/Assets/Art/Textures\`: \`${r.trees[app]}\``);
  out.push('');
  out.push('PLAN A4: every texture has a provenance sidecar. Each .png under apps/*/Assets/Art/Textures/ has exactly one status:', '');
  out.push('- **sidecar**: a tracked `<name>.png.provenance.txt` beside it (declared origin: its `method` field).');
  out.push('- **row**: no sidecar, but a row of that folder\'s `PROVENANCE.md` table whose first cell, backticks stripped, equals the file name exactly (declared origin: the second cell). A name that is a prefix of another row\'s name does not count; a brace row such as `plant_{a,b}.png` names no single file and does not count.');
  out.push('- **missing**: neither.', '');
  out.push('Declared-derived counts the textures whose sidecar says `derived_from_art_reference: yes` or whose row says it is derived from the art reference.', '');
  out.push('**This census reads declarations, not pixels. It cannot prove that no pixel is borrowed from the art reference; it proves only that every texture names an origin, and which origins say they were derived.**', '');
  out.push('## Totals', '');
  out.push(row(['App', 'pngs', 'sidecar', 'row', 'missing', 'declared-derived']), row(['---', '---:', '---:', '---:', '---:', '---:']));
  for (const app of r.apps) {
    const t = totals(r.records.filter(x => x.app === app));
    out.push(row([app, t.pngs, t.sidecar, t.row, t.missing, t.derived]));
  }
  out.push(row(['**all**', ...[all.pngs, all.sidecar, all.row, all.missing, all.derived].map(n => `**${n}**`)]), '');
  const rest = r.records.filter(x => x.status !== 'sidecar');
  out.push('## Textures without a sidecar', '');
  out.push(`${rest.length} of ${all.pngs}. \`row\` shows its declared origin; \`missing\` has none.`, '');
  out.push(row(['Texture', 'Status', 'Declared origin']), row(['---', '---', '---']));
  for (const x of rest) out.push(row([`\`${x.path}\``, x.status, x.status === 'row' ? cell(clip(x.origin)) : '-']));
  out.push('');
  return out.join('\n');
}
