if (a.only === 'duplicates') {
  if (!result.classification) throw new Error(`${CLASSIFICATION} is not tracked at ${result.commit.sha}`);
  fs.writeFileSync(path.join(outDir, 'DUPLICATES.md'), duplicatesMarkdown(result));
} else {
  fs.writeFileSync(path.join(outDir, 'baseline.json'), layout(result) + '\n');
  fs.writeFileSync(path.join(outDir, 'BASELINE.md'), markdown(result));
}
const t = result.totals;
console.log(`commit ${result.commit.sha}`);
console.log(`tracked ${t.tracked.files} files ${t.tracked.bytes} bytes (${t.tracked.mib} MiB); png ${t.png.files} files ${t.png.bytes} bytes (${t.png.mib} MiB)`);
for (const c of result.classes) console.log(`${c.class}: ${c.findings} findings, ${c.bytesSaved} bytes`);
if (result.classification) {
  const c = result.classification;
  console.log(`duplicate groups: cut ${c.cut.groups} (${c.cut.bytes} bytes), both-stay ${c.bothStay.groups} (${c.bothStay.bytes} bytes), unclassified ${c.unclassified.groups}`);
  console.log(`unclassified duplicate groups: ${c.unclassified.groups}`);
  if (c.stale.length) console.log(`stale classification entries: ${c.stale.length}`);
  if (c.handVerdictDiffersFromRule.length) console.log(`hand verdict differs from the keep rule: ${c.handVerdictDiffersFromRule.join(', ')}`);
  if (c.handRiskDiffersFromCensus.length) console.log(`hand risk differs from the census: ${c.handRiskDiffersFromCensus.join(', ')}`);
} else console.log(`${CLASSIFICATION} is not tracked at this commit: duplicate groups unclassified`);
console.log(`wrote ${path.relative(root, outDir).replace(/\\/g, '/')}/${a.only === 'duplicates' ? 'DUPLICATES.md' : 'baseline.json and BASELINE.md'}`);
