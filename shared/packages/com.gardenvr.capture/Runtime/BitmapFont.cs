        public static void Draw(Color32[] pixels, int imageWidth, int imageHeight, int x, int yTop, string text, Color32 ink)
        {
            if (pixels == null || string.IsNullOrEmpty(text)) return;
            int pen = x;
            for (int i = 0; i < text.Length; i++)
            {
                int c = text[i];
                if (c >= FirstChar && c <= LastChar)
                {
                    int o = (c - FirstChar) * GlyphHeight;
                    for (int row = 0; row < GlyphHeight; row++)
                    {
                        byte bits = Data[o + row];
                        if (bits == 0) continue;
                        int py = yTop + row;
                        if (py < 0 || py >= imageHeight) continue;
                        int uy = imageHeight - 1 - py;
                        for (int col = 0; col < GlyphWidth; col++)
                        {
                            if ((bits & (0x80 >> col)) == 0) continue;
                            int px = pen + col;
                            if (px < 0 || px >= imageWidth) continue;
                            pixels[uy * imageWidth + px] = ink;
                        }
                    }
                }
                pen += Advance;
            }
        }
    }
